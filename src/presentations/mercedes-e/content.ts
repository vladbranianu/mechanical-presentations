/** Camera at `dist` from `t`, along `dir` (normalised here). */
const look = (t: Vec3, dir: Vec3, dist: number): CameraView => {
  const l = Math.hypot(...dir);
  return { target: t, position: [t[0] + (dir[0] / l) * dist, t[1] + (dir[1] / l) * dist, t[2] + (dir[2] / l) * dist] };
};

